#ifndef STD_TYPES
#define STD_TYPES
//  unsigned -> u
//  signed -> s
//  char -> 8bit
// 8 bits
typedef signed char s8;
typedef unsigned char u8;
 // 16 bits
typedef signed short int  s16;
typedef unsigned short int u16;

//64 bit 
typedef signed long long int  s64;
typedef unsigned long long int  u64;

//floating ploints
 typedef double d64;
 typedef float f32;
 #endif